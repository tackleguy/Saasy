import {chromium} from 'playwright-core';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const base=process.env.GRAPHICS_URL||'http://127.0.0.1:3100';
const out=new URL('./screens/',import.meta.url);
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1600,height:1000},reducedMotion:'reduce'});
let stage="load";const errors=[];page.on('pageerror',e=>errors.push(stage+": "+String(e)));page.on('console',m=>{if(['warning','error'].includes(m.type()))errors.push(stage+': '+m.type()+': '+m.text());});
await page.goto(base+'/projects/aurelia-tower',{waitUntil:'domcontentloaded',timeout:120000});
await page.waitForSelector('canvas[data-graphics]',{timeout:120000});
await page.getByLabel('Site context',{exact:true}).selectOption('cinematic');
const scene=page.locator('section').filter({has:page.locator('[data-cinematic-dock]')}).last();
await scene.scrollIntoViewIfNeeded();await page.mouse.move(1590,990);await page.waitForTimeout(6000);
const capture=async n=>{await page.screenshot({path:fileURLToPath(new URL(n+'.png',out))});};
await capture('explorer-dock');
stage='map';await page.getByRole('button',{name:'Site map',exact:true}).click();
await page.getByRole('button',{name:'Close site map',exact:true}).click({trial:true});await capture('explorer-map');
await page.getByRole('button',{name:'Close site map',exact:true}).click();
stage='focus';await page.getByLabel('Sun',{exact:true}).selectOption('night');
await page.getByRole('navigation',{name:'Tower zones'}).getByRole('button',{name:/Residential/}).click();
await page.waitForTimeout(4000);await capture('explorer-night-focus');
await page.getByLabel('Scene presentation settings',{exact:true}).click();
await page.getByLabel('Sun',{exact:true}).selectOption('night');await capture('explorer-focus-controls');
await page.getByLabel('Scene presentation settings',{exact:true}).click();
await page.getByRole('button',{name:'Close floor inspector'}).click();
stage="explosion";const slider=page.getByRole('slider',{name:/Explosion/});await slider.focus();await page.keyboard.press('ArrowRight');await page.waitForTimeout(3000);await capture('explorer-exploded');await page.keyboard.press('Home');await page.waitForTimeout(3000);
// Capture must serialize rapid calls and restore drawing size.
stage="capture";const canvas=page.locator('canvas').first();const before=await canvas.evaluate(c=>[c.width,c.height]);let downloads=0;page.on('download',()=>downloads++);
await page.getByRole('button',{name:'Capture cinematic PNG'}).evaluate(button=>{button.click();button.click();button.click();});
await page.waitForTimeout(3500);assert.equal(downloads,1,'Capture must ignore concurrent clicks');assert.deepEqual(await canvas.evaluate(c=>[c.width,c.height]),before,'Capture must restore dimensions');
stage='mobile-tier';await page.setViewportSize({width:390,height:844});await scene.scrollIntoViewIfNeeded();await page.getByLabel('Scene quality',{exact:true}).selectOption('low');await page.waitForTimeout(3500);await capture('explorer-mobile');
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'No page overflow');
await fs.writeFile(new URL('interaction-results.json',out),JSON.stringify({captureDownloads:downloads,restoredDimensions:before,errors},null,2));
console.log(JSON.stringify({captureDownloads:downloads,errorCount:errors.length,errors:[...new Set(errors)].slice(0,8)},null,2));await browser.close();
