/**
 * Writes supabase/migrations/20261023000300_seed_sample_projects.sql from the
 * eight sample projects in src/content/projects.ts, so the public portfolio and
 * customer projects share one table and one loader (src/lib/data/projects.ts).
 *
 *   node --import tsx scripts/supabase/generate-seed.ts
 *
 * Re-run after editing a sample project; the migration upserts by slug.
 */
import { writeFileSync } from "node:fs";
import { PROJECTS } from "../../src/content/projects";

const quote = (s: string) => `'${s.replace(/'/g, "''")}'`;
const rows = PROJECTS.map((p) =>
  `  (${quote(p.slug)}, ${quote(p.name)}, ${quote(p.status)}, ${quote(p.city)}, ${quote(JSON.stringify(p))}::jsonb, true)`,
);
const sql = `-- Sample portfolio: the eight illustrative projects from src/content/projects.ts.
-- Generated by scripts/supabase/generate-seed.ts — do not edit by hand.
-- Public (is_public) and owned by no organization; every customer project
-- uses the same table, document shape and loader.
insert into public.projects (slug, name, status, city, data, is_public) values
${rows.join(",\n")}
on conflict ((coalesce(org_id, '00000000-0000-0000-0000-000000000000'::uuid)), slug)
do update set name = excluded.name, status = excluded.status, city = excluded.city, data = excluded.data, is_public = true;
`;
writeFileSync("supabase/migrations/20261023000300_seed_sample_projects.sql", sql);
console.log(`wrote ${PROJECTS.length} sample projects (${(sql.length / 1024).toFixed(0)} KB)`);
